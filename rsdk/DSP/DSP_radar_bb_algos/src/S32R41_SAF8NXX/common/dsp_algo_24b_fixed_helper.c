void RsdkVMemCpy16(xb_vecNx16 * pOut,
		           xb_vecNx16 * pIn,
					   uint32_t size)
{
	uint32_t idx;
	xb_vecNx16 * out = pOut;
	xb_vecNx16 * in = pIn;
	xb_vecNx16 temp;

	for (idx = 0U; idx < size; idx++)
	{
		BBE_LVNX16_IP(temp, in, 32);
		BBE_SVNX16_IP(temp, out, 32);
	}
}
