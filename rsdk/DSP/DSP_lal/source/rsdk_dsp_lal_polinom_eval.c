void Rsdk_LA_polinomEval_Sof32p8Vif32p8Sif32p8(xb_vecN_2xf32 * pOutput,
                                         xb_vecN_2xf32 const * pInput1,
                                         xb_vecN_2xf32 const * pInput2,
                                                      uint32_t degree)
{
  xb_vecN_2xf32 * pout       = pOutput;
  xb_vecN_2xf32 const * pin1 = pInput1;
  xb_vecN_2xf32 const var    = *pInput2;
 
 xb_vecN_2xf32 sum = *pInput1;
 
  uint32_t i = 0UL;
  for (i = 0UL; i < degree; i++)
  {
    sum = BBE_ADDN_2XF32(BBE_MULN_2XF32(sum, var), pin1[i+1UL]);
  }
  *pout = sum;
}

