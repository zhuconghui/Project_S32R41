void Rsdk_DT_copy_Mof32p8Mif32p8(xb_vecN_2xf32 * __restrict pOutput,
		                         xb_vecN_2xf32 * __restrict pInput,
		                                           uint32_t rows,
		                                           uint32_t cols)
{
	xb_vecN_2xf32 * pin  = pInput;
	xb_vecN_2xf32 * pout = pOutput;
	
	uint32_t iElem;

	for(iElem = 0U; iElem < (rows * cols); iElem++)
	{
    	*pout = *pin;
    	pin++;
    	pout++;
	}
}

