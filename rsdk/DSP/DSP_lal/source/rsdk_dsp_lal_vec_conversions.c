void Rsdk_DT_getRe_Vof32p8Vif32cp8(xb_vecN_2xf32 * __restrict pOutput,
		                                     xb_vecN_2xcf32 * pInput,
                                                     uint32_t size)
{
	xb_vecN_2xf32 * pout = pOutput;
	xb_vecN_2xcf32 * pin = pInput;
	
    uint32_t iElem;
    for (iElem = 0UL; iElem < size; iElem++)
    {
        *pout = BBE_CREALN_2XCF32(*pin);
        pout++;
        pin++;
    }
}

void Rsdk_DT_getIm_Vof32p8Vif32cp8(xb_vecN_2xf32 * __restrict pOutput,
		                                     xb_vecN_2xcf32 * pInput,
                                                     uint32_t size)
{
	xb_vecN_2xf32 * pout = pOutput;
	xb_vecN_2xcf32 * pin = pInput;
	
    uint32_t iElem;
    for (iElem = 0UL; iElem < size; iElem++)
    {
    	*pout = BBE_CIMAGN_2XCF32(*pin);
    	pout++;
    	pin++;
    }
}

