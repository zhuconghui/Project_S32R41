void Rsdk_LA_prod_Sof32p8Vif32p8(xb_vecN_2xf32 * pOutput,
                           xb_vecN_2xf32 const * pInput,
                                        uint32_t size)
{
  uint32_t i;
  xb_vecN_2xf32 const * pin  = pInput;
  xb_vecN_2xf32 * pout = pOutput;
  xb_vecN_2xf32 in, out;

  out = *pin;
  for (i = 1UL; i < size; i++)
  {
    pin++;
    in = *pin;
    out = out * in;
  }
  *pout = out;
}


