void Rsdk_DT_interl_Mof32cp8Mif32p8Mif32p8(xb_vecN_2xcf32 * __restrict pOutput,
		                                               xb_vecN_2xf32 * pInput1,
		                                               xb_vecN_2xf32 * pInput2,
		                                                      uint32_t rows,
		                                                      uint32_t cols)
{
	xb_vecN_2xf32 * pin1  = pInput1;
	xb_vecN_2xf32 * pin2  = pInput2;
	xb_vecN_2xcf32 * pout = pOutput;
	
	uint32_t iElem;
	for(iElem = 0UL; iElem < (rows * cols); iElem++)
	{
		*pout = BBE_CMPLXN_2XF32((*pin2), (*pin1));
		pout++;
		pin1++;
		pin2++;
	}
}

void Rsdk_DT_deinterl_Mof32p8Mof32p8Mif32cp8(xb_vecN_2xf32 * __restrict pOutput1,
                                             xb_vecN_2xf32 * __restrict pOutput2,
                                                       xb_vecN_2xcf32 * pInput,
                                                               uint32_t rows,
                                                               uint32_t cols)
{
	xb_vecN_2xcf32 * pin  = pInput;
	xb_vecN_2xf32 * pout1 = pOutput1;
	xb_vecN_2xf32 * pout2 = pOutput2;
	
	uint32_t iElem;
	for(iElem = 0UL; iElem < (rows * cols); iElem++)
	{
		*pout1 = BBE_CREALN_2XCF32(*pin);
		*pout2 = BBE_CIMAGN_2XCF32(*pin);
		pout1++;
		pout2++;
		pin++;
	}
}

