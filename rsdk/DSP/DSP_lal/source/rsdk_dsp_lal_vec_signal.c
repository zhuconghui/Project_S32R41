void Rsdk_SP_SNR_Vof32p8Vif32p8Vif32p8(xb_vecN_2xf32 * pOutput,
                                 xb_vecN_2xf32 const * pInput1,
                                 xb_vecN_2xf32 const * pInput2,
                                              uint32_t size)
{
	xb_vecN_2xf32 * pout = pOutput;
	
    uint32_t iElem;
    xb_vecN_2xf32 log10ratio[size], ratio[size];
    xb_vecN_2xf32 const *pSignal = pInput1;
    xb_vecN_2xf32 const *pNoise  = pInput2;
    xb_vecN_2xf32 const10f = 10.0f;
    xb_vecN_2xf32 res;
	vboolN_2 flags;

    for (iElem = 0UL; iElem < size; iElem++)
    {
		res = (xb_vecN_2xf32)0x7f800000; //infinity
		flags = (vboolN_2)(pNoise[iElem] != (xb_vecN_2xf32)0.0F);
		BBE_DIVN_2XF32T(res, pSignal[iElem], pNoise[iElem], flags);
        res = BBE_ABSN_2XF32(res);
        ratio[iElem] = res;
    }

    Rsdk_EF_log10_Vof32p8Vif32p8(log10ratio, ratio, size);

    for (iElem = 0; iElem < size; iElem++)
    {
        pout[iElem] = const10f * log10ratio[iElem];
    }
}

